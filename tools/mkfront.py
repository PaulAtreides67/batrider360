"""The N64 front end's pictures for the 360, from the kit's N64 manual art (ref/n64_manual_art).

usage: python3 tools/mkfront.py <project dir>

- (test 10, user: no N64 logos in any build: the title overlay of the N64 logo + RAIZING line is gone; the title
  shows the arcade's own logo layers)
- splash: the COIN-OP GAME STUDIO logo on black, 480x640 upright.
It is stored turned into the board's orientation (640x480, as the game's texture: board x = 639 - upright y,
board y = upright x), RGBA, deflated. Writes build/gen/front_assets.h and work/front_preview.png.
"""
import sys
import zlib

import numpy as np
from PIL import Image, ImageFilter

P = sys.argv[1]
ART = P + '/ref/n64_manual_art/'


def rgba(name, alpha):
    im = Image.open(ART + name).convert('RGB')
    a = Image.open(ART + alpha).convert('L')
    im.putalpha(a)
    return im


def crop_alpha(im):
    return im.crop(im.getchannel('A').point(lambda v: 255 if v > 8 else 0).getbbox())


def place(im, w, h, x, y, size):
    """im resized to w x h (premultiplied Lanczos) at (x, y) on a transparent canvas of size."""
    a = np.asarray(im).astype(np.float64) / 255
    pm = np.dstack([a[..., :3] * a[..., 3:], a[..., 3:]])
    pmi = Image.fromarray((pm * 255 + 0.5).astype(np.uint8), 'RGBA')
    r = np.asarray(pmi.resize((w, h), Image.LANCZOS)).astype(np.float64) / 255
    out = np.zeros((size[1], size[0], 4))
    h2, w2 = min(h, size[1] - y), min(w, size[0] - x)
    out[y:y + h2, x:x + w2] = r[:h2, :w2]
    return out                                   # premultiplied


def over(pm, bg):
    return pm[..., :3] + bg * (1 - pm[..., 3:])


def fit(im, n64, bg, box, w0, x0, y0):
    """the width and place (1x) where im over bg looks most like the N64 picture inside box"""
    asp = im.size[1] / im.size[0]
    y_a, y_b, x_a, x_b = box
    best = None
    for w in range(w0 - 6, w0 + 7):
        h = round(w * asp)
        for x in range(x0 - 4, x0 + 5):
            for y in range(y0 - 4, y0 + 5):
                c = over(place(im, w, h, x, y, (240, 320)), bg)
                e = np.abs(c[y_a:y_b, x_a:x_b] - n64[y_a:y_b, x_a:x_b]).mean()
                if best is None or e < best[0]:
                    best = (e, w, h, x, y)
    print('fit: error %.4f, %dx%d at %d,%d' % best)
    return best[1:]


def to_board(up):
    """upright 640 rows x 480 columns -> board 480 rows x 640 columns: board[ty][tx] = up[639 - tx][ty]"""
    return np.ascontiguousarray(up[::-1].transpose(1, 0, 2))


def c_array(name, data):
    z = zlib.compress(data, 9)
    s = 'static const uint8_t %s[%d] = {\n' % (name, len(z))
    for i in range(0, len(z), 24):
        s += '\t' + ','.join('%d' % b for b in z[i:i + 24]) + ',\n'
    return s + '};\n', len(z)


def main():
    # test 10 (user): no N64 logo over the title any more; the arcade's own logo layers are drawn
    co = Image.open(ART + 'coinop.png').convert('RGB').resize((448, 448), Image.LANCZOS)
    sp = np.zeros((640, 480, 4), np.uint8)
    sp[..., 3] = 255
    sp[96:544, 16:464, :3] = np.asarray(co)

    Image.fromarray(sp[..., :3]).save(P + '/work/front_preview.png')

    out = '/* Generated by tools/mkfront.py from ref/n64_manual_art: the N64 front end\'s pictures, 640x480 RGBA in the\n'
    out += ' * board\'s orientation, deflated: the splash only (test 10: no N64 title logo). */\n'
    out += 'enum { FRONT_W = 640, FRONT_H = 480 };\n'
    b, nb = c_array('splash_z', to_board(sp).tobytes())
    open(P + '/build/gen/front_assets.h', 'w').write(out + b)
    print('splash %d bytes' % nb)


if __name__ == '__main__':
    main()
