"""CHASE!'s 68000 patch (the batrider-chase project's) as runs of new bytes, for the 360 to apply at load.

usage: python3 tools/mkpatch.py <batriderj program dir> <prg_chase.bin> <out .h>

The program dir holds prg0b.u22, prg1b.u23, prg2.u21, prg3.u24 (batriderj, as MAME's set; romset.c checks
their CRCs at load, so only the new bytes are kept). prg_chase.bin is batrider-chase/build/prg_chase.bin
(tools/patch.py there). Writes a C header: chase_runs[] = {address, length, offset into chase_bytes}.
"""
import sys
import zlib


def program(d):
    def rd(n):
        return open(d + '/' + n, 'rb').read()
    e0, o0, e1, o1 = rd('prg0b.u22'), rd('prg1b.u23'), rd('prg2.u21'), rd('prg3.u24')
    return b''.join(bytes(p) for p in zip(e0, o0)) + b''.join(bytes(p) for p in zip(e1, o1))


def main():
    orig = program(sys.argv[1])
    new = open(sys.argv[2], 'rb').read()
    assert len(orig) == len(new) == 0x200000
    runs = []
    a = 0
    while a < len(new):
        if orig[a] == new[a]:
            a += 1
            continue
        b = a
        # runs merge across gaps of up to 8 unchanged bytes
        while b < len(new) and (orig[b] != new[b] or any(orig[c] != new[c] for c in range(b, min(b + 8, len(new))))):
            b += 1
        runs.append((a, b))
        a = b
    data = b''.join(new[a:b] for a, b in runs)
    with open(sys.argv[3], 'w') as f:
        f.write('/* Generated by tools/mkpatch.py from batrider-chase/build/prg_chase.bin: CHASE! on batriderj. */\n')
        f.write('/* program CRC32 before %08X, after %08X */\n' % (zlib.crc32(orig) & 0xffffffff,
                                                               zlib.crc32(new) & 0xffffffff))
        f.write('#define CHASE_CRC_AFTER 0x%08Xu\n' % (zlib.crc32(new) & 0xffffffff))
        f.write('static const struct { uint32_t addr; uint16_t len; uint16_t off; } chase_runs[] = {\n')
        off = 0
        for a, b in runs:
            f.write('\t{ 0x%06X, %d, %d },\n' % (a, b - a, off))
            off += b - a
        f.write('};\nstatic const uint8_t chase_bytes[%d] = {\n' % len(data))
        for i in range(0, len(data), 16):
            f.write('\t' + ', '.join('0x%02X' % x for x in data[i:i + 16]) + ',\n')
        f.write('};\n')
    print('%d runs, %d bytes' % (len(runs), len(data)))


if __name__ == '__main__':
    main()
